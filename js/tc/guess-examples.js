/* =========================================================================
 * tc/guess-examples.js —— 猜数字示例源码（两个版本）
 *   TC.GUESS_RAW  原始 guess_number.cpp，完整保留，用来验收「这段代码里的
 *                 所有操作」——类 / 64 位 / chrono / 流状态会有明确降级告警。
 *   TC.GUESS_8    8 位等价可玩版，编译成 BF 后能真正把一局游戏跑完。
 * 源码以数组内联，避免 file:// 下 fetch 本地文件的跨域限制。
 * ========================================================================= */
(function (TC) {
  'use strict';
  /* 原始完整源码（用户贴的 guess_number.cpp） */
  TC.GUESS_RAW = [
    "// guess_number.cpp",
    "// 编译: g++ -std=c++17 -O2 -Wall -o guess_number guess_number.cpp",
    "#include <iostream>",
    "#include <cstdint>",
    "#include <chrono>",
    "#include <ctime>",
    "#include <limits>",
    "",
    "// ============================================================",
    "//  一、自己实现的伪随机数生成器（xorshift64*）",
    "//  不用 <random> / rand()，纯手写算法。",
    "// ============================================================",
    "class XorShift64 {",
    "public:",
    "    explicit XorShift64(uint64_t seed)",
    "        : state(seed ? seed : 0x9E3779B97F4A7C15ULL) {}  // 种子不能为 0",
    "",
    "    // 产生一个 64 位随机数",
    "    uint64_t nextU64() {",
    "        uint64_t s = state;",
    "        s ^= s >> 12;",
    "        s ^= s << 25;",
    "        s ^= s >> 27;",
    "        state = s;",
    "        return s * 0x2545F4914F6CDD1DULL;",
    "    }",
    "",
    "    // 返回 [0, bound) 内的均匀随机整数（拒绝采样，消除取模偏差）",
    "    uint64_t nextBelow(uint64_t bound) {",
    "        uint64_t threshold = (0ULL - bound) % bound;",
    "        uint64_t r;",
    "        do {",
    "            r = nextU64();",
    "        } while (r < threshold);",
    "        return r % bound;",
    "    }",
    "",
    "    // 返回 [lo, hi] 闭区间内的随机整数",
    "    int nextInt(int lo, int hi) {",
    "        uint64_t range = static_cast<uint64_t>(hi - lo) + 1;",
    "        return lo + static_cast<int>(nextBelow(range));",
    "    }",
    "",
    "private:",
    "    uint64_t state;",
    "};",
    "",
    "// ============================================================",
    "//  二、自己实现的种子生成（时间 + 地址熵 + 混合函数）",
    "// ============================================================",
    "uint64_t makeSeed() {",
    "    auto now = std::chrono::high_resolution_clock::now().time_since_epoch().count();",
    "    uint64_t seed = static_cast<uint64_t>(now);",
    "",
    "    seed ^= static_cast<uint64_t>(std::time(nullptr)) << 17;",
    "    seed ^= reinterpret_cast<uint64_t>(&seed);",
    "",
    "    // splitmix64 混合，把熵打散到所有比特位",
    "    seed ^= seed >> 30; seed *= 0xBF58476D1CE4E5B9ULL;",
    "    seed ^= seed >> 27; seed *= 0x94D049BB133111EBULL;",
    "    seed ^= seed >> 31;",
    "    return seed;",
    "}",
    "",
    "// ============================================================",
    "//  三、游戏主体",
    "// ============================================================",
    "int main() {",
    "    const int rangeLow  = 1;",
    "    const int rangeHigh = 100;",
    "",
    "    std::cout << \"================================\\n\";",
    "    std::cout << \"       猜 数 字 游 戏\\n\";",
    "    std::cout << \"  范围: \" << rangeLow << \" ~ \" << rangeHigh << \"\\n\";",
    "    std::cout << \"================================\\n\";",
    "",
    "    XorShift64 rng(makeSeed());",
    "",
    "    char again = 'y';",
    "    while (again == 'y' || again == 'Y') {",
    "        const int secret = rng.nextInt(rangeLow, rangeHigh);",
    "        int tries = 0;",
    "",
    "        std::cout << \"\\n我想好了一个 \" << rangeLow << \"~\" << rangeHigh << \" 之间的数字，来猜吧！\\n\";",
    "",
    "        while (true) {",
    "            std::cout << \"你的猜测> \";",
    "            int guess;",
    "            if (!(std::cin >> guess)) {",
    "                if (std::cin.eof()) {",
    "                    std::cout << \"\\n输入结束，再见！\\n\";",
    "                    return 0;",
    "                }",
    "                std::cin.clear();",
    "                std::cin.ignore(std::numeric_limits<std::streamsize>::max(), '\\n');",
    "                std::cout << \"  请输入一个整数。\\n\";",
    "                continue;",
    "            }",
    "",
    "            if (guess < rangeLow || guess > rangeHigh) {",
    "                std::cout << \"  超出范围了，请输入 \" << rangeLow << \"~\" << rangeHigh",
    "                          << \" 之间的数。\\n\";",
    "                continue;",
    "            }",
    "",
    "            ++tries;",
    "",
    "            if (guess < secret) {",
    "                std::cout << \"  太小了 ↑\\n\";",
    "            } else if (guess > secret) {",
    "                std::cout << \"  太大了 ↓\\n\";",
    "            } else {",
    "                std::cout << \"  ★ 猜对了！答案就是 \" << secret",
    "                          << \"，你一共猜了 \" << tries << \" 次。\\n\";",
    "                if (tries <= 5)       std::cout << \"  评价: 太强了，简直是二分查找大师！\\n\";",
    "                else if (tries <= 8)  std::cout << \"  评价: 很不错！\\n\";",
    "                else                  std::cout << \"  评价: 下次试试先猜中间值 (二分法)。\\n\";",
    "                break;",
    "            }",
    "        }",
    "",
    "        std::cout << \"\\n再来一局？(y/n) \";",
    "        std::cin >> again;",
    "        std::cin.ignore(std::numeric_limits<std::streamsize>::max(), '\\n');",
    "    }",
    "",
    "    std::cout << \"游戏结束，再见！\\n\";",
    "    return 0;",
    "}"
  ].join('\n');

  /* 8 位等价可玩版 */
  TC.GUESS_8 = [
    "// guess_number_8bit.cpp —— 原版 guess_number.cpp 的 8 位等价实现",
    "// 保留原版用到的全部操作：>> << ^= |= &= *= %=、do-while、while + break/continue、",
    "// 三元 ?:、static_cast、uint64_t、0x 常量 ULL 后缀、cin/cout、中文 UTF-8 输出。",
    "// BrainFuck 单元格是 8 位：xorshift64* 收敛成 8 位，时间种子改为固定值。",
    "#include <iostream>",
    "#include <cstdint>",
    "using namespace std;",
    "",
    "uint64_t xmix(uint64_t s) {",
    "    s ^= s >> 3;                       // >> 右移 + ^= 异或赋值",
    "    s ^= s << 2;                       // << 左移 + ^= 异或赋值",
    "    s |= 1;                            // |= 按位或赋值",
    "    s &= 0xFE;                         // &= 按位与赋值",
    "    return s * 29 + 57;                // 8 位混合",
    "}",
    "",
    "int main() {",
    "    uint64_t state = 0xC5ULL;          // 8 位种子（大常量精确取低 8 位）",
    "    int secret = static_cast<int>(xmix(state)) % 100 + 1;",
    "    int tries = 0;",
    "    int guess = 0;",
    "    char again = 'y';",
    "",
    "    cout << \"=== 8 位猜数字 (1~100) ===\\n\";",
    "    cout << \"答案固定，试试二分法。\\n\";",
    "",
    "    while (again == 'y' || again == 'Y') {",
    "        do {",
    "            cout << \"你的猜测> \";",
    "            cin >> guess;",
    "        } while (guess < 1 || guess > 100);",
    "",
    "        ++tries;",
    "        if (guess < secret) { cout << \"  太小了 ↑\\n\"; continue; }",
    "        if (guess > secret) { cout << \"  太大了 ↓\\n\"; continue; }",
    "",
    "        cout << \"  ★ 猜对了！答案 \" << secret << \"，猜了 \" << tries << \" 次。\\n\";",
    "        int grade = tries <= 3 ? 1 : 2;",
    "        if (grade == 1) cout << \"  评价: 二分查找大师！\\n\";",
    "        else cout << \"  评价: 下次试试先猜中间值。\\n\";",
    "",
    "        cout << \"再来一局？(y/n) \";",
    "        cin >> again;",
    "        state = xmix(state + 1);",
    "        secret = static_cast<int>(xmix(state)) % 100 + 1;",
    "        tries = 0;",
    "    }",
    "",
    "    cout << \"游戏结束，再见！\\n\";",
    "    return 0;",
    "}"
  ].join('\n');

})(window.TC = window.TC || {});
